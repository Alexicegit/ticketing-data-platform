-- ============================================================
-- TICKET SALES
-- ============================================================

MERGE INTO RAW.TICKET_SALES AS t
USING RAW.STG_TICKET_SALES AS s
ON t.TICKET_ID = s.TICKET_ID

WHEN MATCHED
    AND s.UPDATED_AT > t.UPDATED_AT
THEN
UPDATE SET
    t.EVENT_ID        = s.EVENT_ID,
    t.ORGANIZER_ID    = s.ORGANIZER_ID,
    t.RESELLER_ID     = s.RESELLER_ID,
    t.SELLER_TYPE     = s.SELLER_TYPE,
    t.SELLER_ID       = s.SELLER_ID,
    t.SELLER_NAME     = s.SELLER_NAME,
    t.CUSTOMER_ID     = s.CUSTOMER_ID,
    t.SALES_CHANNEL   = s.SALES_CHANNEL,
    t.QUANTITY        = s.QUANTITY,
    t.UNIT_PRICE      = s.UNIT_PRICE,
    t.TOTAL_AMOUNT    = s.TOTAL_AMOUNT,
    t.PURCHASE_DATE   = s.PURCHASE_DATE,
    t.BATCH_ID        = s.BATCH_ID,
    t.UPDATED_AT      = s.UPDATED_AT,
    t.LOAD_TS         = s.LOAD_TS,
    t.SOURCE_SYSTEM   = s.SOURCE_SYSTEM

WHEN NOT MATCHED THEN
INSERT (
    TICKET_ID,
    EVENT_ID,
    ORGANIZER_ID,
    RESELLER_ID,
    SELLER_TYPE,
    SELLER_ID,
    SELLER_NAME,
    CUSTOMER_ID,
    SALES_CHANNEL,
    QUANTITY,
    UNIT_PRICE,
    TOTAL_AMOUNT,
    PURCHASE_DATE,
    BATCH_ID,
    UPDATED_AT,
    LOAD_TS,
    SOURCE_SYSTEM
)
VALUES (
    s.TICKET_ID,
    s.EVENT_ID,
    s.ORGANIZER_ID,
    s.RESELLER_ID,
    s.SELLER_TYPE,
    s.SELLER_ID,
    s.SELLER_NAME,
    s.CUSTOMER_ID,
    s.SALES_CHANNEL,
    s.QUANTITY,
    s.UNIT_PRICE,
    s.TOTAL_AMOUNT,
    s.PURCHASE_DATE,
    s.BATCH_ID,
    s.UPDATED_AT,
    s.LOAD_TS,
    s.SOURCE_SYSTEM
);