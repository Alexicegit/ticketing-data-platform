-- ============================================================
-- ORGANIZERS
-- ============================================================

MERGE INTO RAW.ORGANIZERS T
USING RAW.STG_ORGANIZERS S

ON T.ORGANIZER_ID = S.ORGANIZER_ID


WHEN MATCHED THEN UPDATE SET

T.ORGANIZER_NAME = S.ORGANIZER_NAME,
T.COUNTRY = S.COUNTRY,
T.REGION = S.REGION,
T.LOAD_TS = S.LOAD_TS,
T.SOURCE_SYSTEM = S.SOURCE_SYSTEM,
T.BATCH_ID = S.BATCH_ID,
T.UPDATED_AT = S.UPDATED_AT


WHEN NOT MATCHED THEN INSERT
(
ORGANIZER_ID,
ORGANIZER_NAME,
COUNTRY,
REGION,
LOAD_TS,
SOURCE_SYSTEM,
BATCH_ID,
UPDATED_AT
)

VALUES
(
S.ORGANIZER_ID,
S.ORGANIZER_NAME,
S.COUNTRY,
S.REGION,
S.LOAD_TS,
S.SOURCE_SYSTEM,
S.BATCH_ID,
S.UPDATED_AT
);



